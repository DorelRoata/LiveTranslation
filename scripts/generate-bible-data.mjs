// Regenerates src/bible-data.js: the 66 books, verses per chapter, and the
// verse-numbering maps between Bibles. Run by hand only when the data needs to
// change: node scripts/generate-bible-data.mjs
//
// Source: Copenhagen Alliance versification mappings (eng = KJV numbering,
// org = Hebrew/Greek original, rso = Russian Synodal).
// https://github.com/Copenhagen-Alliance/versification-specification
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://raw.githubusercontent.com/Copenhagen-Alliance/versification-specification/master/versification-mappings/standard-mappings';
const SCHEMES = ['eng', 'org', 'rso'];
const CODES = [
  'GEN', 'EXO', 'LEV', 'NUM', 'DEU', 'JOS', 'JDG', 'RUT', '1SA', '2SA', '1KI', '2KI', '1CH', '2CH', 'EZR', 'NEH', 'EST',
  'JOB', 'PSA', 'PRO', 'ECC', 'SNG', 'ISA', 'JER', 'LAM', 'EZK', 'DAN', 'HOS', 'JOL', 'AMO', 'OBA', 'JON', 'MIC', 'NAM',
  'HAB', 'ZEP', 'HAG', 'ZEC', 'MAL', 'MAT', 'MRK', 'LUK', 'JHN', 'ACT', 'ROM', '1CO', '2CO', 'GAL', 'EPH', 'PHP', 'COL',
  '1TH', '2TH', '1TI', '2TI', 'TIT', 'PHM', 'HEB', 'JAS', '1PE', '2PE', '1JN', '2JN', '3JN', 'JUD', 'REV'
];

const RANGE = /^([1-3A-Z]{3}) (\d+):(\d+)(?:-(\d+))?$/;

function parseRange(text) {
  const match = RANGE.exec(text.trim());
  if (!match) return null;
  const book = CODES.indexOf(match[1]) + 1;
  if (!book) return null;
  const start = Number(match[3]);
  return [book, Number(match[2]), start, match[4] ? Number(match[4]) : start];
}

const data = {};
for (const scheme of SCHEMES) {
  const response = await fetch(`${SOURCE}/${scheme}.json`);
  if (!response.ok) throw new Error(`${scheme}.json: HTTP ${response.status}`);
  data[scheme] = await response.json();
}

const verseCounts = {};
for (const scheme of SCHEMES) {
  verseCounts[scheme] = CODES.map(code => (data[scheme].maxVerses[code] || []).map(Number));
}

// [book, chapter, firstVerse, lastVerse] in the scheme => the same verses in
// org. A few ranges differ in length where a Psalm title is merged or split.
const toOriginal = {};
for (const scheme of ['eng', 'rso']) {
  toOriginal[scheme] = [];
  for (const [from, to] of Object.entries(data[scheme].mappedVerses)) {
    const a = parseRange(from);
    const b = parseRange(to);
    if (a && b) toOriginal[scheme].push([...a, ...b]);
  }
}

const header = `// Generated by scripts/generate-bible-data.mjs. Do not edit by hand.
// Verse numbering from the Copenhagen Alliance versification mappings:
// eng = King James numbering (most English, Romanian, Spanish Bibles),
// org = Hebrew/Greek original (Psalm titles counted as verses),
// rso = Russian Synodal (Greek Psalm numbering).
`;
const body = [
  `export const BOOK_CODES = ${JSON.stringify(CODES)};`,
  `// Verses in each chapter, per numbering scheme, indexed [book - 1][chapter - 1].`,
  `export const VERSE_COUNTS = ${JSON.stringify(verseCounts)};`,
  `// [book, chapter, firstVerse, lastVerse, origBook, origChapter, origFirst, origLast]`,
  `export const TO_ORIGINAL = ${JSON.stringify(toOriginal)};`
].join('\n');

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'bible-data.js');
await writeFile(target, `${header}${body}\n`);
console.log(`Wrote ${target}: ${toOriginal.eng.length} eng and ${toOriginal.rso.length} rso mappings.`);
